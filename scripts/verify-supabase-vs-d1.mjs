function sqlIdent(value) {
  return `"${String(value).replaceAll('"', '""')}"`;
}

function psSingleQuoted(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function parseWranglerJson(stdout) {
  const text = String(stdout || "")
    .replace(/^\uFEFF/, "")
    .trim();

  if (!text) {
    throw new Error("Wrangler returned no JSON output.");
  }

  try {
    return JSON.parse(text);
  } catch {}

  // Defensive fallback in case a warning appears before the JSON.
  for (let i = 0; i < text.length; i += 1) {
    if (text[i] !== "[" && text[i] !== "{") continue;

    try {
      return JSON.parse(text.slice(i));
    } catch {}
  }

  throw new Error(
    `Could not parse Wrangler JSON output. First output: ${text.slice(0, 800)}`,
  );
}

function extractRows(payload, tableName) {
  // Wrangler 4 d1 execute --json returns QueryResult[]:
  // [{ results: [...], success: true, meta: {...}, query: "..." }]
  if (!Array.isArray(payload) || payload.length < 1) {
    throw new Error(
      `Unexpected Wrangler JSON shape for ${tableName}: expected a result array.`,
    );
  }

  const queryResult = payload.find(
    (entry) => entry && Array.isArray(entry.results),
  );

  if (!queryResult) {
    throw new Error(
      `Wrangler succeeded for ${tableName}, but no results array was returned.`,
    );
  }

  if (queryResult.success === false) {
    throw new Error(`D1 reported query failure for ${tableName}.`);
  }

  return queryResult.results;
}

function queryD1(spec) {
  if (process.platform !== "win32") {
    throw new Error(
      "This verifier build is intended for the current Windows migration workstation.",
    );
  }

  const sql =
    `SELECT ${spec.columns.map(sqlIdent).join(", ")} ` +
    `FROM ${sqlIdent(spec.table)} ORDER BY ${sqlIdent("id")} ASC;`;

  const token = crypto.randomBytes(8).toString("hex");
  const psPath = path.join(
    os.tmpdir(),
    `99s-stage4-verify-${spec.table}-${token}.ps1`,
  );

  // Passing SQL through a PowerShell variable prevents cmd.exe from splitting
  // the SQL into separate Wrangler arguments.
  const psScript = [
    "$ErrorActionPreference = 'Stop'",
    `$database = ${psSingleQuoted(DATABASE_NAME)}`,
    `$config = ${psSingleQuoted(CONFIG_PATH)}`,
    "$sql = @'",
    sql,
    "'@",
    "$npx = (Get-Command npx.cmd -ErrorAction Stop).Source",
    "& $npx wrangler d1 execute $database --remote --command $sql --json --yes -c $config",
    "exit $LASTEXITCODE",
    "",
  ].join("\r\n");

  fs.writeFileSync(psPath, psScript, "utf8");

  try {
    const powershell =
      process.env.SystemRoot
        ? path.join(
            process.env.SystemRoot,
            "System32",
            "WindowsPowerShell",
            "v1.0",
            "powershell.exe",
          )
        : "powershell.exe";

    const result = spawnSync(
      powershell,
      [
        "-NoLogo",
        "-NoProfile",
        "-NonInteractive",
        "-ExecutionPolicy",
        "Bypass",
        "-File",
        psPath,
      ],
      {
        encoding: "utf8",
        windowsHide: true,
        maxBuffer: 40 * 1024 * 1024,
        env: process.env,
      },
    );

    if (result.error) {
      throw new Error(
        `Could not launch PowerShell/Wrangler for ${spec.table}: ` +
          `${result.error.code || "spawn_error"} ${result.error.message}`,
      );
    }

    if (result.status !== 0) {
      throw new Error(
        [
          `Wrangler failed for ${spec.table}.`,
          `Exit code: ${String(result.status)}`,
          result.stderr ? `stderr:\n${result.stderr.trim()}` : "",
          result.stdout ? `stdout:\n${result.stdout.trim()}` : "",
        ]
          .filter(Boolean)
          .join("\n"),
      );
    }

    const payload = parseWranglerJson(result.stdout);
    return extractRows(payload, spec.table);
  } finally {
    try {
      fs.unlinkSync(psPath);
    } catch {}
  }
}

function normalizeValue(value, column, spec) {
  if (value === null || value === undefined) {
    return null;
  }

  if (spec.booleans.includes(column)) {
    return Number(value) === 1;
  }

  if (spec.dates.includes(column)) {
    const date = new Date(value);

    if (Number.isNaN(date.getTime())) {
      throw new Error(
        `Invalid D1 date in ${spec.table}.${column}: ${String(value).slice(0, 120)}`,
      );
    }

    return date.toISOString();
  }

  return String(value);
}

function canonicalHash(rows, spec) {
  const hash = crypto.createHash("sha256");

  for (const row of rows) {
    const canonical = {};

    for (const column of spec.columns) {
      canonical[column] = normalizeValue(
        row[column],
        column,
        spec,
      );
    }

    hash.update(JSON.stringify(canonical));
    hash.update("\n");
  }

  return hash.digest("hex");
}

function loadManifest() {
  let manifest;

  try {
    manifest = JSON.parse(
      fs.readFileSync(MANIFEST_PATH, "utf8"),
    );
  } catch (error) {
    throw new Error(
      `Could not read Stage 4C manifest: ` +
        `${error instanceof Error ? error.message : String(error)}`,
    );
  }

  if (!manifest || typeof manifest !== "object" || !manifest.tables) {
    throw new Error(
      "Stage 4C manifest is invalid: missing tables object.",
    );
  }

  return manifest;
}

async function main() {
  const manifest = loadManifest();

  console.log("");
  console.log(
    "99's Guide — Stage 4D Snapshot Integrity Verification v7",
  );
  console.log(
    "---------------------------------------------------------",
  );
  console.log("Supabase connection: NOT REQUIRED");
  console.log("Source of truth:     Stage 4C Supabase snapshot manifest");
  console.log("D1:                  read-only");
  console.log("");

  let allPassed = true;

  for (const spec of specs) {
    const expected = manifest.tables?.[spec.table];

    if (
      !expected ||
      !Number.isInteger(expected.rows) ||
      typeof expected.sha256 !== "string"
    ) {
      throw new Error(
        `Manifest is missing valid row-count/hash metadata for ${spec.table}.`,
      );
    }

    const d1Rows = queryD1(spec);
    const actualHash = canonicalHash(d1Rows, spec);

    const countPass =
      d1Rows.length === expected.rows;

    const hashPass =
      actualHash.toLowerCase() ===
      expected.sha256.toLowerCase();

    const pass = countPass && hashPass;

    console.log(
      `${spec.table.padEnd(14)} ` +
        `Snapshot=${String(expected.rows).padStart(4)} ` +
        `D1=${String(d1Rows.length).padStart(4)} ` +
        `${pass ? "PASS" : "FAIL"}`,
    );

    if (!pass) {
      allPassed = false;

      if (!countPass) {
        console.log(
          `  Row count mismatch: expected=${expected.rows}, actual=${d1Rows.length}`,
        );
      }

      if (!hashPass) {
        console.log("  SHA-256 content hash mismatch.");
        console.log(`  Expected: ${expected.sha256}`);
        console.log(`  Actual:   ${actualHash}`);
      }
    }
  }

  console.log("");

  if (!allPassed) {
    throw new Error(
      "SNAPSHOT VERIFICATION FAILED — do not proceed to traffic cutover.",
    );
  }

  console.log("EXACT SNAPSHOT VERIFICATION PASS");
  console.log(
    "Every D1 table matches the exact Stage 4C Supabase snapshot by row count and SHA-256 content hash.",
  );
  console.log("No database was modified.");
  console.log("");
  console.log(
    `Snapshot generated at: ${manifest.generatedAt || "unknown"}`,
  );
}

main().catch((error) => {
  console.error("");
  console.error(
    error instanceof Error
      ? error.message
      : error,
  );
  process.exitCode = 1;
});
